"""Build docs/gold_graph_metrics.md: every arm x backbone x gold variant.

One entry point so the report is regenerated, not hand-edited, whenever a run
or the gold set changes.

Usage:
  uv run python -m art6.ontology.diagnostics.build_graph_report
"""

from __future__ import annotations

import json
from pathlib import Path

from art6.ontology.diagnostics import score_against_gold as sag
from art6.ontology.diagnostics.score_against_gold import prf1 as prf1_local
from art6.ontology.diagnostics.score_graph_metrics import run as graph_run

REPO_ROOT = Path(__file__).resolve().parents[3]
GOLD_DIR = REPO_ROOT / "annotation/gold"
OUT = REPO_ROOT / "docs/gold_graph_metrics.md"

RUNS = {
    "gemma": REPO_ROOT / "results/final_gemma_gold30",
    "terra-mixed": REPO_ROOT / "results/final_terra_mixed_gold30",
}
ARMS = ["C1", "C2", "C3", "C4"]
VARIANTS = [
    (None, "all gold events"),
    ("level_investigative", "excluding level=Investigative"),
    ("matter_investigation", "excluding matter=Investigation"),
]


def pct(x):
    return f"{x:.1%}" if x is not None else "--"


def _matter_trace():
    """Where matter survives and where it stops, along the gemma gold30 run.

    Counted from the artefacts themselves rather than asserted, so this section
    cannot drift away from the run it describes.
    """
    run = REPO_ROOT / "results/final_gemma_gold30"
    total = with_matter = 0
    for path in (run / "stage1").glob("*.compress.json"):
        payload = json.loads(path.read_text())["payload"]
        for event in payload.get("events", []):
            total += 1
            if event.get("matter"):
                with_matter += 1
    bundles = (run / "bundles.jsonl").read_text().count("matter")

    def triples(sub):
        return sum(p.read_text().count("hasMatter") for p in (run / sub).glob("*.ttl"))

    return [
        (
            "stage 1 (`compress.json`) events carrying `matter`",
            f"{with_matter}/{total} ({with_matter / total:.0%})" if total else "n/a",
        ),
        ("`matter` mentions surviving into the rendered digest", str(bundles)),
        (
            "C1 `echr:hasMatter` triples (stage 2 from the RAW judgment)",
            str(triples("C1_C2/raw")),
        ),
        (
            "C3 `echr:hasMatter` triples (stage 2 from the DIGEST)",
            str(triples("C3_C4/raw")),
        ),
    ]


def edge_prf(e):
    p = e["correct"] / e["arm_edges"] if e["arm_edges"] else None
    r = e["correct"] / e["gold_edges"] if e["gold_edges"] else None
    f = 2 * p * r / (p + r) if p and r else None
    return p, r, f


def main() -> None:
    docs = json.loads((GOLD_DIR / "manifest.json").read_text())["documents"]
    if docs and "line_id" not in docs[0]:
        docs = [{**d, "line_id": f"L{i}"} for i, d in enumerate(docs, 1)]

    results = {}
    for backbone, run_dir in RUNS.items():
        for arm in ARMS:
            for exclude, _ in VARIANTS:
                results[(backbone, arm, exclude)] = graph_run(
                    run_dir, arm, docs, GOLD_DIR, exclude
                )

    # event-level scores from the canonical scorer, both modes, incl. C0
    event_scores = {}
    sag.GOLD_DIR = GOLD_DIR
    sag.MANIFEST = GOLD_DIR / "manifest.json"
    for backbone, run_dir in RUNS.items():
        for arm in ["C0"] + ARMS:
            for mode in ["existence", "date_quote"]:
                event_scores[(backbone, arm, mode)] = sag.score_arm(
                    run_dir, arm, docs, mode=mode
                )

    lines = []
    w = lines.append
    w("# Gold graph metrics — gold30, all 30 documents")
    w("")
    w(
        "Generated by `art6/ontology/diagnostics/build_graph_report.py`. Do not hand-edit."
    )
    w("")
    w("All 30 gold documents are scored, including the four that legitimately")
    w("carry zero events (`001-194305`, `001-223977`, `001-225667`, `001-235021`).")
    w("They contribute no recall denominator but do contribute precision signal:")
    w("anything an arm emits on them is a false positive.")
    w("")
    w("`gemma` = gemma-4-31b throughout. `terra-mixed` = gpt-5.6-terra at stage 1,")
    w("gemma-4-31b at stages 2/3, identical `compress_v2.txt` prompt and config, so")
    w("the only variable between them is the stage-1 backbone. C0 is gemma in BOTH")
    w("columns — the schema-light baseline never routes through the stage-1 model —")
    w("so the standalone terra C0 is reported separately at the end.")
    w("")

    # ---- 1. event scores ------------------------------------------------
    w("## 1. Event-level scores (the headline ablation)")
    w("")
    for mode in ["date_quote", "existence"]:
        w(f"### mode: `{mode}`")
        w("")
        w(
            "| arm | gemma P | gemma R | gemma F1 | terra-mixed P | terra-mixed R | terra-mixed F1 |"
        )
        w("|---|---|---|---|---|---|---|")
        for arm in ["C0"] + ARMS:
            g = event_scores[("gemma", arm, mode)]
            t = event_scores[("terra-mixed", arm, mode)]
            w(
                f"| {arm} | {pct(g['precision'])} | {pct(g['recall'])} | **{pct(g['f1'])}** "
                f"| {pct(t['precision'])} | {pct(t['recall'])} | **{pct(t['f1'])}** |"
            )
        w("")

    # ---- 2. gold variants ------------------------------------------------
    w("## 2. Gold variants — what excluding investigative events does")
    w("")
    w("`level=Investigative` is 82 of 317 gold events (26%); `matter=Investigation`")
    w("is 43. An excluded event takes its edges with it, so chain recall is not")
    w("penalised for links into events the variant deliberately removed.")
    w("")
    w("| backbone | arm | variant | P | R | F1 | gold events |")
    w("|---|---|---|---|---|---|---|")
    for backbone in RUNS:
        for arm in ARMS:
            for exclude, label in VARIANTS:
                r = results[(backbone, arm, exclude)]
                gold_n = r["matched"] + r["gold_only"]
                w(
                    f"| {backbone} | {arm} | {label} | {pct(r['precision'])} "
                    f"| {pct(r['recall'])} | **{pct(r['f1'])}** | {gold_n} |"
                )
    w("")

    # ---- 3. matter -------------------------------------------------------
    w("## 3. Matter — is it captured, and does it agree?")
    w("")
    w("`echr:hasMatter` is deliberately NOT universal in the ontology (omit rather")
    w("than force a value onto a purely procedural act), so *both sides empty* is")
    w("agreement, not a shared miss, and is counted separately below.")
    w("")
    w("Counts are over ALIGNED event pairs only — an event the arm never found")
    w("cannot have its matter judged.")
    w("")
    w(
        "| backbone | arm | gold ev. w/ matter | arm ev. w/ matter | aligned | both empty | exact set | partial | disagree |"
    )
    w("|---|---|---|---|---|---|---|---|---|")
    for backbone in RUNS:
        for arm in ARMS:
            m = results[(backbone, arm, None)]["matter"]
            w(
                f"| {backbone} | {arm} | {m['gold_events_with_matter']} "
                f"| {m['arm_events_with_matter']} | {m['aligned']} | {m['both_empty']} "
                f"| {m['exact_set_match']} | {m['partial_overlap']} | {m['disagree']} |"
            )
    w("")
    w("Label-level (multi-valued, so counted as labels not events):")
    w("")
    w("| backbone | arm | shared labels | gold-only labels | arm-only labels |")
    w("|---|---|---|---|---|")
    for backbone in RUNS:
        for arm in ARMS:
            m = results[(backbone, arm, None)]["matter"]
            w(
                f"| {backbone} | {arm} | {m['intersection_labels']} "
                f"| {m['gold_only_labels']} | {m['arm_only_labels']} |"
            )
    w("")
    w("### Matter is captured, then lost in stage 2 of the compressed arm")
    w("")
    w("The compressed arm (C3/C4 — **the arm the corpus is built with**) carries")
    w("far less matter than the raw arm (C1/C2), and the loss is NOT at stage 1.")
    w("Traced on `final_gemma_gold30`:")
    w("")
    for label, value in _matter_trace():
        w(f"- {label}: **{value}**")
    w("")
    w("Stage 1 extracts matter on 78% of events and the rendered digest still")
    w("carries it, but stage 2 emits `echr:hasMatter` on barely a quarter as many")
    w("events when reading the digest as it does when reading the raw judgment.")
    w("`compress_v2.txt` has a whole `CLASSIFY THE MATTER` section and `facts.txt`")
    w("names matter too, so this is a stage-2 fidelity gap, not a missing")
    w("instruction. It matters for downstream use: matter is the obvious axis for")
    w("clustering or filtering the corpus, and the corpus arm is the one losing it.")
    w("")

    # ---- 4. chain edges --------------------------------------------------
    w("## 4. Chain edges")
    w("")
    w("**Read these on their own scale, not against event F1.** An arm edge can")
    w("only be counted correct if BOTH endpoints aligned to gold events, so this")
    w("measure is conjunctive and bounded above by roughly (event recall)². A")
    w("chain-edge F1 well below event F1 is the expected shape of the measure, not")
    w("a separate failure.")
    w("")
    for kind in ["follows", "part_of", "occurs_during"]:
        w(f"### `{kind}`")
        w("")
        w(
            "| backbone | arm | gold edges | arm edges | alignable | correct | P | R | F1 |"
        )
        w("|---|---|---|---|---|---|---|---|---|")
        for backbone in RUNS:
            for arm in ARMS:
                e = results[(backbone, arm, None)]["edges"][kind]
                p, r, f = edge_prf(e)
                w(
                    f"| {backbone} | {arm} | {e['gold_edges']} | {e['arm_edges']} "
                    f"| {e['arm_edges_alignable']} | {e['correct']} "
                    f"| {pct(p)} | {pct(r)} | **{pct(f)}** |"
                )
        w("")

    # ---- 5. shape --------------------------------------------------------
    w("## 5. Graph shape vs gold")
    w("")
    w("Over the `follows` relation. **Chains** are weakly connected components (a")
    w("standalone event is a chain of one). **Depth** is the longest directed path")
    w("in edges, so a lone event is depth 0. **Paths** counts maximal source→sink")
    w("routes, which separates a graph that fans out from one that runs straight at")
    w("equal depth. Gold figures repeat per row because gold does not change.")
    w("")
    w("| backbone | arm | events | edges | chains | max depth | mean depth | paths |")
    w("|---|---|---|---|---|---|---|---|")
    gold_shape = results[("gemma", "C4", None)]["gold_shape"]
    w(
        f"| **gold** | — | {gold_shape['events']:.0f} | {gold_shape['edges']:.0f} "
        f"| {gold_shape['chains']:.0f} | {gold_shape['max_depth']:.0f} "
        f"| {gold_shape['mean_depth'] / 30:.2f} | {gold_shape['paths']:.0f} |"
    )
    for backbone in RUNS:
        for arm in ARMS:
            s = results[(backbone, arm, None)]["arm_shape"]
            docs_n = results[(backbone, arm, None)]["docs"] or 1
            w(
                f"| {backbone} | {arm} | {s['events']:.0f} | {s['edges']:.0f} "
                f"| {s['chains']:.0f} | {s['max_depth']:.0f} "
                f"| {s['mean_depth'] / docs_n:.2f} | {s['paths']:.0f} |"
            )
    w("")
    w("(`max depth` is summed per document, so it reads as a total across the 30,")
    w("not a single document's deepest chain; `mean depth` is per document.)")
    w("")

    # ---- 6. standalone terra C0 -----------------------------------------
    w("## 6. Standalone terra C0")
    w("")
    w("C0 in the tables above is gemma in both columns, because the schema-light")
    w("baseline is one flat call on the raw judgment and never routes through the")
    w("stage-1 backbone. `results/final_terra_mixed_gold30/C0_terra` is the same")
    w("condition run on gpt-5.6-terra, which is the only true terra-vs-gemma")
    w("comparison at C0.")
    w("")
    w("| model | mode | P | R | F1 |")
    w("|---|---|---|---|---|")
    c0_terra_dir = REPO_ROOT / "results/final_terra_mixed_gold30/C0_terra"
    for mode in ["date_quote", "existence"]:
        score_doc = (
            sag.score_document if mode == "existence" else sag.score_document_date_quote
        )
        tm = tg = tam = tao = 0
        for doc in docs:
            gold = sag.load_gold(doc["case_id"])
            arm = sag.load_c0(c0_terra_dir / f"input.{doc['line_id']}.o1.json")
            r = score_doc(doc["case_id"], gold, arm)
            tm += r.matched
            tg += r.gold_only
            tam += r.arm_matched
            tao += r.arm_only
        s = prf1_local(tm, tg, tam, tao)
        g = event_scores[("gemma", "C0", mode)]
        w(
            f"| gpt-5.6-terra | `{mode}` | {pct(s['precision'])} | {pct(s['recall'])} "
            f"| **{pct(s['f1'])}** |"
        )
        w(
            f"| gemma-4-31b | `{mode}` | {pct(g['precision'])} | {pct(g['recall'])} "
            f"| **{pct(g['f1'])}** |"
        )
    w("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
